// Вызывается из handleButtonAction() при BTN_MENU_ENTER.
// После возврата необходимо вызвать loadSettings() для обновления активных таймеров.
void RunSettingsMode();

// Применить настройки из savedData к активным модулям.
// Устанавливает яркость дисплея и состояние TaraLock/AutoZero.
// Вызывается: при старте, после сохранения настроек, при таймауте/отмене (для восстановления).
void ApplySettings();
