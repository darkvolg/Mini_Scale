// ================================================================
// SettingsMode.h — меню пользовательских настроек
// ================================================================
// Доступные настройки:
//   1. Яркость дисплея: LOW / MED / HIGH
//   2. Автовыключение: 1 мин / 3 мин / 5 мин / OFF
//   3. Автозатухание: 30с / 60с / 120с
//   4. Auto-zero: OFF / ON
//   5. Единицы: кг / г
//   6. Tara Lock: OFF / ON
//
// Управление одной кнопкой:
//   Короткое нажатие (< CAL_LONG_PRESS_MS) — изменить значение параметра
//   Длинное нажатие  (>= CAL_LONG_PRESS_MS) — перейти к следующему параметру
//   Длинное нажатие на последнем пункте — SAVE и выход
//
// Таймаут бездействия: SETTINGS_IDLE_TIMEOUT_MS (30 сек) → выход без сохранения

// Таблица значений таймаутов автовыключения (мс): 1мин/3мин/5мин/OFF(0)
// Не static — используется в Mini_Scale.ino в функции loadSettings() для
// преобразования savedData.auto_off_mode (индекс) → реальный таймаут в мс.
extern const unsigned long autoOffValues[];

// Таблица значений таймаутов автозатухания (мс): 30с/60с/120с
// Не static — используется в Mini_Scale.ino в loadSettings().
extern const unsigned long autoDimValues[];

// Запустить меню настроек.
