#pragma once
#include "Config.h"

// ================================================================
// BatteryControl.h — мониторинг состояния LiPo аккумулятора
// ================================================================
// Считывает напряжение батареи через делитель напряжения на пине A0,
// применяет EMA-фильтрацию и переводит в проценты по кривой разряда LiPo.
//
// Схема: LiPo (4.2V max) → делитель R1/R2 (коэффициент 0.762) → A0 (3.2V max)
// ADC ESP8266: 10 бит (0..1023), макс. входное напряжение 3.2V (Wemos D1 Mini)

// Первичная инициализация: считывание ADC и инициализация EMA без сглаживания.
// Устанавливает охранный период BAT_GRACE_MS для исключения ложного критического срабатывания.
void Battery_Init();

// Обновление состояния батареи. Вызывается каждую итерацию loop().
// Два независимых таймера:
//   - Мигание иконки: каждые BLINK_INTERVAL_MS (1500 мс) при заряде < BAT_LOW_PERCENT
//   - Считывание ADC: каждые BAT_READ_INTERVAL_MS (5000 мс) с EMA-фильтрацией
void Battery_Update();

// Текущее напряжение батареи (В). Вычисляется из EMA-сглаженного ADC.
float Battery_GetVoltage();

// Текущий процент заряда [0..100].
// Рассчитывается по кусочно-линейной кривой LiPo (BAT_PROFILE_LIPO=1)
// или линейно (BAT_PROFILE_LIPO=0).
int Battery_GetPercent();

// Заряд ниже порога «низкий»? (bat_percent < BAT_LOW_PERCENT = 10%)
// При низком заряде иконка начинает мигать.
bool Battery_IsLow();

// Заряд ниже критического порога? (bat_percent <= BAT_CRITICAL_PERCENT = 5%)
// При критическом заряде устройство начинает процедуру выключения.
// Возвращает false в течение BAT_GRACE_MS после старта (охранный период).
// Возвращает false если батарея не подключена (ADC < BAT_MIN_ADC_CONNECTED).
bool Battery_IsCritical();

// Текущая фаза мигания иконки батареи.
// true = иконка скрыта (фаза «выключено»).
// false = иконка видна (нормальное состояние или фаза «включено»).
// Используется в Display_ShowMain для параметра batLowBlink.
bool Battery_BlinkPhase();
