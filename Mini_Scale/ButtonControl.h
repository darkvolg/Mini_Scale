#pragma once
#include "Config.h"

// ================================================================
// ButtonControl.h — конечный автомат управления кнопкой
// ================================================================
// Реализует:
//   - Устранение дребезга при нажатии и отпускании
//   - Классификацию действий по длительности удержания
//   - Механизм «двойного нажатия» для входа в меню настроек

// Действия кнопки, возвращаемые из Button_Update() в каждой итерации loop().
// Обрабатываются в handleButtonAction() в Mini_Scale.ino.
enum ButtonAction {
  BTN_NONE,           // Нет действия: кнопка не нажата или идёт антидребезг
  BTN_SHOW_HINT,      // Кнопка удерживается — обновить прогресс-бар на дисплее
  BTN_MENU_PROMPT,    // Удержано >= MENU_HOLD_MS (2 сек) — показать "Press again"
  BTN_MENU_ENTER,     // Второе нажатие в пределах MENU_CONFIRM_WINDOW_MS — войти в меню
  BTN_MENU_CANCEL,    // Окно MENU_CONFIRM_WINDOW_MS истекло без второго нажатия
  BTN_TARE,           // Отпущено после >= BUTTON_TARE_MS (10 сек) — тарирование
  BTN_UNDO            // Отпущено после >= BUTTON_UNDO_MS (15 сек) — отмена тарирования
};

// Внутренние состояния конечного автомата кнопки (приватные для ButtonControl.cpp).
// Объявлены здесь чтобы Button_IsHolding() мог проверять текущее состояние.
enum ButtonState {
  BTN_IDLE,              // Ожидание нажатия (кнопка не нажата)
  BTN_DEBOUNCE_PRESS,    // Антидребезг нажатия (ждём DEBOUNCE_MS)
  BTN_HOLDING,           // Кнопка удерживается (нажата и подтверждена)
  BTN_DEBOUNCE_RELEASE   // Антидребезг отпускания (ждём DEBOUNCE_MS)
};

// Таймер последней активности (нажатие кнопки, изменение веса).
// Определён в Mini_Scale.ino, используется как ButtonControl, так и loop().
// ButtonControl обновляет его при каждом подтверждённом событии кнопки.
extern unsigned long lastActivityTime;

// Настройка пина кнопки как INPUT_PULLUP.
// Вызывается один раз в setup(). Кнопка подключена между BUTTON_PIN и GND.
void Button_Init();

// Опрос конечного автомата кнопки. Вызывается каждую итерацию loop().
// Должен вызываться ДО Scale_Update() чтобы не пропустить короткие нажатия
// пока HX711 блокирует шину (~300 мс).
// Возвращает: текущее действие (BTN_NONE если нет события)
ButtonAction Button_Update();

// Проверка: кнопка сейчас удерживается (состояние BTN_HOLDING)?
// Используется в loop() для: отображения прогресс-бара и подавления light sleep.
bool Button_IsHolding();

// Время удержания кнопки с момента подтверждённого нажатия (мс).
// Возвращает 0 если кнопка не в состоянии BTN_HOLDING.
// Используется в Display_ShowMain для прогресс-бара и текстовых подсказок.
unsigned long Button_HoldElapsed();
