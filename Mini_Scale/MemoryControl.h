#pragma once
#include <EEPROM.h>
#include "Config.h"

// ================================================================
// MemoryControl.h — хранение данных в EEPROM (Flash) ESP8266
// ================================================================
// Реализует:
//   - Wear-leveling: данные записываются round-robin по EEPROM_SLOTS (4) слотам
//   - CRC16-CCITT: проверка целостности каждого слота
//   - Миграция данных: v2 → v4, v3 → v4 при обновлении прошивки
//   - Троттлинг записи: не чаще EEPROM_MIN_INTERVAL_MS (1 час) через Memory_Save()
//   - Определение «самого свежего» слота по полю slot_seq (wrap-around сравнение)

// ================================================================
// Структура данных EEPROM (версия 4 = текущая)
// ================================================================
// FIX-8: __attribute__((packed)) — гарантируем одинаковый layout байтов
// независимо от компилятора/платформы. Без packed компилятор может добавить
// выравнивающие байты и layout v4 не совпал бы с ожидаемым при чтении.
struct __attribute__((packed)) EEPROM_Data {
  uint32_t magic_key;           // Признак валидных данных: MAGIC_NUMBER (0x2A2B3C)
  uint8_t  version;             // Версия структуры: FIRMWARE_VERSION (4)
  uint8_t  slot_seq;            // Монотонный счётчик записей [0..255, overflow OK]
                                // Используется для поиска «самого свежего» слота
  long tare_offset;             // Смещение тары: offset HX711 (вычитается из raw ADC)
  long backup_offset;           // Резервная копия tare_offset для операции undo
  float last_weight;            // Последний сохранённый вес (кг) — для session_delta
  float cal_factor;             // Калибровочный коэффициент HX711 (raw_units/кг)
  float backup_last_weight;     // Резервная копия last_weight для операции undo
  uint8_t brightness_level;     // Индекс яркости дисплея: 0=LOW, 1=MED, 2=HIGH
  uint8_t auto_off_mode;        // Индекс автовыключения: 0=1мин, 1=3мин, 2=5мин, 3=OFF
  uint8_t auto_dim_mode;        // Индекс автозатухания: 0=30с, 1=60с, 2=120с
  uint8_t auto_zero_on;         // Авто-нуль: 0=выкл, 1=вкл
  uint8_t units_mode;           // Единицы: 0=кг, 1=г
  uint8_t tara_lock_on;         // Блокировка тарирования: 0=выкл, 1=вкл (также отключает авто-нуль)
  uint16_t crc16;               // CRC16-CCITT всех полей выше (без самого crc16)
};

// Общий размер EEPROM.begin(): 4 слота + 16 байт запаса (для будущих версий)
#define EEPROM_SIZE_COMPUTED (sizeof(EEPROM_Data) * EEPROM_SLOTS + 16)

// Глобальная рабочая копия данных из EEPROM.
// Все модули читают и изменяют только эту переменную.
// Запись во Flash происходит через Memory_Save() или Memory_ForceSave().
extern EEPROM_Data savedData;

// Инициализация: загрузить данные из самого свежего валидного слота.
// При отсутствии валидных данных: попытка миграции v3→v4 или v2→v4, иначе factory reset.
void Memory_Init();

// Сохранить с троттлингом (не чаще EEPROM_MIN_INTERVAL_MS = 1 час).
// Вызывается каждую итерацию loop() для отложенного сохранения last_weight.
// Пропускает запись если данные не изменились (payloadEqual проверка).
void Memory_Save();

// Принудительное немедленное сохранение (без проверки таймаута троттлинга).
// Использовать при критических событиях: тарирование, undo, critical battery, вход в меню.
// Всё равно пропускает запись если данные не изменились.
void Memory_ForceSave();

// Пометить данные изменёнными для отложенного сохранения через Memory_Save().
// Вызывать при любом изменении savedData, если немедленная запись не нужна.
void Memory_MarkDirty();
